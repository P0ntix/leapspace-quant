def _function_index(source: str) -> List[Tuple[int, int, str]]:
    """(start_line, end_line, name) for every function in a source file.

    AST when the file parses, a line scan when it does not - a file being
    rewritten underneath us must not crash the report.
    """
    try:
        tree = ast.parse(source)
    except (SyntaxError, ValueError):
        out: List[Tuple[int, int, str]] = []
        cur = "<module>"
        start = 1
        for i, line in enumerate(source.splitlines(), 1):
            m = re.match(r"^def\s+(\w+)", line)
            if m:
                out.append((start, i - 1, cur))
                cur = m.group(1)
                start = i
        out.append((start, 10 ** 9, cur))
        return out
    out = []
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            out.append((node.lineno, node.end_lineno or node.lineno,
                        node.name))
    out.sort()
    return out


def _enclosing(funcs: Sequence[Tuple[int, int, str]], line: int) -> str:
    """The innermost function containing a line, or "<module>"."""
    best = "<module>"
    best_span = 10 ** 12
    for start, end, name in funcs:
        if start <= line <= (end if end < 10 ** 9 else 10 ** 9):
            span = end - start
            if span < best_span:
                best_span = span
                best = name
    return best


def _scan_enforcement(root: str) -> Dict[str, Any]:
    """Read the four enforcement modules and index their tokens."""
    modules: Dict[str, Dict[str, Any]] = {}
    for name in ENFORCEMENT_MODULES:
        path = os.path.join(root, "leapspace", name)
        text, err = _read_text(path)
        if text is None:
            modules[name] = {"present": False, "error": err,
                             "lines": [], "funcs": []}
            continue
        lines = text.splitlines()
        modules[name] = {
            "present": True,
            "error": None,
            "lines": lines,
            "funcs": _function_index(text),
            "path": path,
        }
    return modules


def _code_thresholds(modules: Dict[str, Dict[str, Any]]) -> Dict[str, Any]:
    """The gate's OWN threshold table, parsed out of edge.py.

    The specification's threshold column says what a source PUBLISHES.
    This says what the code actually compares against. Where they differ
    the report states both, because "the criterion is enforced" and "the
    published number is what rejects a wallet" are different claims.
    """
    mod = modules.get("edge.py") or {}
    if not mod.get("present"):
        return {}
    text = "\n".join(mod["lines"])
    m = re.search(r"ANALYST_CHOICES\s*:\s*Dict\[str, Any\]\s*=\s*\{(.*?)\n\}",
                  text, re.S)
    if not m:
        return {}
    out: Dict[str, Any] = {}
    for key, value in re.findall(r'"([a-z_]+)":\s*([0-9.]+)\s*,', m.group(1)):
        try:
            out[key] = float(value)
        except ValueError:
            out[key] = value
    return out


def _coverage_row(crit: Dict[str, Any],
                  modules: Dict[str, Dict[str, Any]],
                  code_thresholds: Dict[str, Any]
                  ) -> Dict[str, Any]:
    """One coverage row: is this criterion enforced, and where."""
    key = str(crit.get("key") or "")
    authority = str(crit.get("authority") or "")
    analyst_choice = (authority.startswith("NONE")
                      or "analyst choice" in authority.lower())
    probes = CRITERION_PROBES.get(key, [])
    hits: List[Dict[str, Any]] = []
    gate_hits: List[Dict[str, Any]] = []
    disclosure_hits: List[Dict[str, Any]] = []
    for fname, pattern, kind in probes:
        mod = modules.get(fname) or {}
        if not mod.get("present"):
            continue
        rx = re.compile(pattern)
        for i, line in enumerate(mod["lines"], 1):
            if rx.search(line):
                hit = {"file": fname,
                       "function": _enclosing(mod["funcs"], i),
                       "line": i,
                       "kind": kind,
                       "code": line.strip()[:140]}
                hits.append(hit)
                if kind == "gate":
                    gate_hits.append(hit)
                elif kind == "disclosure":
                    disclosure_hits.append(hit)
                break  # one hit per probe is enough to place it
    gated = bool(gate_hits)
    disclosed = bool(disclosure_hits) and not gated
    enforced = gated or disclosed
    implemented = bool(hits)
    where = "; ".join(sorted({f"{h['file']}:{h['function']}" for h in hits}))
    if gated:
        kind = "gate"
        gap = ""
    elif disclosed:
        kind = "disclosure"
        gap = ("DISCLOSED, not gated: the required label is attached to "
               "every result, so the criterion is satisfied on every run, "
               "but no threshold can reject a wallet on it")
    elif implemented:
        kind = "computed-only"
        gap = ("computed or reported in code, but NOT enforced: no gate "
               "in the four enforcement modules can reject a wallet on "
               "this criterion")
    else:
        kind = "not-implemented"
        gap = ("NOT IMPLEMENTED: no recognisable implementation token for "
               "this criterion was found in " + ", ".join(ENFORCEMENT_MODULES))
    # What the code actually compares against, where the criterion has
    # a published threshold.
    code_key = CRITERION_TO_CODE_THRESHOLD.get(key)
    applied = code_thresholds.get(code_key) if code_key else None
    spec_threshold = crit.get("threshold")
    threshold_matches = None
    if applied is not None and isinstance(spec_threshold, (int, float)):
        threshold_matches = (float(applied) == float(spec_threshold))
    return {
        "key": key,
        "label": crit.get("label"),
        "threshold": crit.get("threshold"),
        "threshold_source": crit.get("threshold_source"),
        "tag": crit.get("tag"),
        "authority": authority,
        "url": crit.get("url"),
        "analyst_choice": analyst_choice,
        "published_standard": not analyst_choice,
        "enforced": enforced,
        "enforcement_kind": kind,
        "implemented": implemented,
        "gated": gated,
        "where": where,
        "gap": gap,
        "applied_threshold": applied,
        "applied_threshold_key": code_key,
        "threshold_matches_spec": threshold_matches,
        "hits": hits,
        "note": CRITERION_NOTES.get(key, ""),
    }


def _section_criteria_coverage(root: str) -> Dict[str, Any]:
    """The enforcement status of the criteria in the spec JSON."""
    rel = os.path.join("leapspace", "data", "consistency_criteria.json")
    path = os.path.join(root, rel)
    spec, err = _read_json(path)
    if spec is None:
        sec = _absent("criteria_coverage", path,
                       "the criteria specification is missing, so no "
                       "criterion can be scored for enforcement")
        sec["missing_input"] = rel
        return sec
    criteria = [c for c in (spec.get("criteria") or [])
                if isinstance(c, dict)]
    flukes = [t for t in (spec.get("fluke_tests") or [])
              if isinstance(t, dict)]
    modules = _scan_enforcement(root)
    thresholds = _code_thresholds(modules)
    rows = [_coverage_row(c, modules, thresholds) for c in criteria]
    missing_modules = [n for n in ENFORCEMENT_MODULES
                       if not (modules.get(n) or {}).get("present")]
    n_enforced = sum(1 for r in rows if r["enforced"])
    n_gated = sum(1 for r in rows if r.get("gated"))
    n_disclosed = sum(1 for r in rows
                      if r.get("enforcement_kind") == "disclosure")
    n_impl = sum(1 for r in rows if r["implemented"])
    n_analyst = sum(1 for r in rows if r["analyst_choice"])
    fluke_rows = []
    for t in flukes:
        auth = str(t.get("authority") or "")
        fluke_rows.append({
            "key": t.get("key"),
            "rejects_when": t.get("rejects_when"),
            "threshold": t.get("threshold"),
            "authority": auth,
            "analyst_choice": (auth.startswith("NONE")
                                or "analyst choice" in auth.lower()),
            "published_standard": not (auth.startswith("NONE")
                                       or "analyst choice" in auth.lower()),
            "severity": t.get("severity"),
        })
    sec = _base("criteria_coverage", [rel] + [
        os.path.join("leapspace", n) for n in ENFORCEMENT_MODULES])
    sec.update({
        "spec_version": spec.get("version"),
        "spec_compiled": spec.get("compiled"),
        "n_criteria": len(criteria),
        "n_fluke_tests": len(flukes),
        "rows": rows,
        "fluke_tests": fluke_rows,
        "n_enforced": n_enforced,
        "n_gated": n_gated,
        "n_disclosed": n_disclosed,
        "n_implemented_not_gated": n_impl - n_enforced,
        "n_not_implemented": len(rows) - n_impl,
        "n_analyst_choice": n_analyst,
        "n_published_standard": len(rows) - n_analyst,
        "enforcement_modules": list(ENFORCEMENT_MODULES),
        "enforcement_modules_missing": missing_modules,
        "scan_method": (
            "each criterion key is matched against a list of specific "
            "implementation tokens in the four enforcement modules; a "
            "token inside a gate function marks the criterion ENFORCED, a "
            "token outside one marks it implemented but not gated"),
        "analyst_choice_note": (
            "a criterion whose authority starts with NONE, or names an "
            "analyst choice, has NO published standard behind it. It is "
            "reported as an operating parameter of this package and is "
            "never presented as a published standard."),
    })
    return sec


