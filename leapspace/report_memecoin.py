def _prov_line(sec: Dict[str, Any]) -> str:
    prov = sec.get("provenance") or DERIVED
    srcs = ", ".join(sec.get("source_files") or []) or "no source file"
    status = sec.get("status")
    extra = "" if status == "ok" else f" · status: **{status}**"
    return f"**Provenance:** `{prov}` · **Sources:** {srcs}{extra}"


