def _section_social_edge(root: str) -> Dict[str, Any]:
    """The narrative cohort and any stored community-size series."""
    rel_cohort = os.path.join("leapspace", "state", "narrative_cohort.json")
    cohort, err = _read_json(os.path.join(root, rel_cohort))
    snaps = []
    if isinstance(cohort, dict):
        snaps = [s for s in (cohort.get("snapshots") or [])
                 if isinstance(s, dict)]
    if not snaps:
        sec = _absent("social_edge", os.path.join(root, rel_cohort),
                       "no narrative-cohort snapshots are stored, so the "
                       "cohort size and the specificity split are unknown")
        sec["missing_input"] = rel_cohort
        return sec

    seen: Dict[str, Dict[str, Any]] = {}
    per_snapshot: List[Dict[str, Any]] = []
    for s in snaps:
        rows = [r for r in (s.get("rows") or []) if isinstance(r, dict)]
        niche = sum(1 for r in rows if r.get("is_niche"))
        per_snapshot.append({"ts": s.get("ts"), "n": s.get("n"),
                             "n_rows": len(rows), "n_niche": niche,
                             "n_generic": len(rows) - niche})
        for r in rows:
            mint = r.get("mint")
            if mint and mint not in seen:
                seen[mint] = r
    niche_total = sum(1 for r in seen.values() if r.get("is_niche"))

    # Community-size series, if any were collected.
    series: List[Dict[str, Any]] = []
    for sub in ("social_series", "holder_series"):
        d = os.path.join(root, "leapspace", "state", sub)
        if not os.path.isdir(d):
            continue
        for fn in sorted(os.listdir(d)):
            if not fn.endswith(".json"):
                continue
            blob, _ = _read_json(os.path.join(d, fn))
            if not isinstance(blob, dict):
                continue
            ss = [x for x in (blob.get("snapshots") or [])
                  if isinstance(x, dict)]
            if not ss:
                continue
            first, last = ss[0], ss[-1]
            series.append({
                "kind": sub,
                "file": os.path.join("leapspace", "state", sub, fn),
                "chain": blob.get("chain"),
                "mint": blob.get("mint"),
                "n_snapshots": len(ss),
                "first_ts": first.get("ts"),
                "last_ts": last.get("ts"),
                "span_seconds": (last.get("ts") - first.get("ts"))
                if isinstance(last.get("ts"), int)
                and isinstance(first.get("ts"), int) else None,
                "telegram_members": last.get("telegram_members"),
                "discord_members": last.get("discord_members"),
                "holder_count": last.get("holder_count"),
                "provenance": last.get("provenance"),
                "source": last.get("source"),
                "member_counts_constant": (
                    len({(x.get("telegram_members"), x.get("discord_members"))
                         for x in ss}) == 1),
                "holder_count_constant": (
                    len({x.get("holder_count") for x in ss}) == 1),
            })

    # Has any wallet been measured against a member-count series?
    lead_hits: List[str] = []
    for base in (os.path.join(root, "reports"),
                 os.path.join(root, "leapspace", "state")):
        if not os.path.isdir(base):
            continue
        for dirpath, _dirnames, filenames in os.walk(base):
            for fn in filenames:
                if not fn.endswith(".json"):
                    continue
                text, _ = _read_text(os.path.join(dirpath, fn))
                if text and "lead_time" in text:
                    lead_hits.append(os.path.relpath(
                        os.path.join(dirpath, fn), root))
    n_series_flat = sum(1 for s in series
                        if s.get("member_counts_constant")
                        or s.get("holder_count_constant"))

    sec = _base("social_edge", [rel_cohort] + [s["file"] for s in series])
    sec.update({
        "cohort_snapshots": len(snaps),
        "cohort_distinct_mints": len(seen),
        "cohort_max_snapshot_n": max((int(s.get("n") or 0) for s in snaps),
                                      default=0),
        "specificity_split": {
            "n_niche": niche_total,
            "n_generic": len(seen) - niche_total,
            "basis": ("distinct mints across all stored snapshots, "
                      "counted from the is_niche flag each row carries"),
            "per_snapshot": per_snapshot,
        },
        "community_size_series": series,
        "n_series_stored": len(series),
        "n_series_with_constant_counts": n_series_flat,
        "measured_lead_times": None,
        "measured_lead_times_note": (
            "NO WALLET HAS YET BEEN MEASURED AGAINST A REAL MEMBER-COUNT "
            "SERIES. No artefact on disk records a lead time between a "
            "wallet's buy and a community-size event."),
        "why_not_measurable": (
            "A member-count series only becomes a SERIES over time: the "
            "endpoints expose the CURRENT count, so the series has to be "
            "sampled repeatedly, and a lead time needs at least two "
            "observations that bracket the wallet's purchase. The stored "
            "series cover minutes, not days, and their member counts do "
            "not move, so no threshold crossing can be located inside "
            "them. Until the series has been collected over a real "
            "interval, the honest answer is NOT YET MEASURABLE - not "
            "'no effect' and not a lead time computed from a flat line."),
        "lead_time_artefacts_found": lead_hits,
        "narrative_classifier_note": (
            "the specificity score is a weighted classifier over free "
            "signals that separate a community footprint from a trend "
            "clone. Its weights and keyword list are analyst choices and "
            "are re-scorable; it measures the PRESENCE of a community "
            "footprint, not attention, sentiment or community size."),
    })
    return sec


