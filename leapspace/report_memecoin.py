def _status_counts(blob: Dict[str, Any]) -> Dict[str, int]:
    counts = {s: 0 for s in WHITELIST_STATUSES}
    for e in (blob.get("entries") or {}).values():
        if isinstance(e, dict):
            st = str(e.get("status") or "UNKNOWN")
            counts[st] = counts.get(st, 0) + 1
    return counts


def _section_whitelist(root: str) -> Dict[str, Any]:
    """The whitelist registry: statuses, promotions, retirements.

    Two artefacts hold a whitelist: the state registry at
    `leapspace/state/whitelist.json` and the copy embedded in the
    priced-edge result file. They can disagree - a re-run overwrites the
    state registry while the result file keeps the snapshot it was
    written with. The report therefore shows the state registry as the
    live record AND says whether the embedded copy agrees with it.
    """
    src = _whitelist_blob(root)
    state = src["state"]
    embedded = src["embedded"]
    if not state["present"] and not embedded["present"]:
        sec = _absent("whitelist",
                       os.path.join(root, state["path"]),
                       "neither the state whitelist nor the whitelist "
                       "embedded in the priced-edge file is present")
        return sec
    state_blob = state["blob"] or {}
    emb_blob = embedded["blob"] or {}
    # The state file is the registry; the embedded copy is the same
    # registry as it stood when the gate ran.
    blob = state_blob if state["present"] else emb_blob
    entries = blob.get("entries") or {}
    events = blob.get("events") or []
    rejected = blob.get("rejected") or []

    status_counts = _status_counts(blob)
    status_counts_embedded = _status_counts(emb_blob) if emb_blob else {}

    rows: List[Dict[str, Any]] = []
    for key, e in sorted(entries.items()):
        if not isinstance(e, dict):
            continue
        hist = e.get("history") or []
        last = hist[-1] if hist else {}
        rows.append({
            "key": key,
            "address": e.get("address"),
            "chain": e.get("chain"),
            "status": e.get("status"),
            "first_seen": e.get("first_seen"),
            "last_evaluated_at": e.get("last_evaluated_at"),
            "promoted_at": e.get("promoted_at"),
            "promoted_reason": e.get("promoted_reason"),
            "retired_at": e.get("retired_at"),
            "retired_reason": e.get("retired_reason"),
            "rejected_at": e.get("rejected_at"),
            "rejected_reason": e.get("rejected_reason"),
            "n_history_entries": len(hist),
            "last_verdict": last.get("verdict"),
            "last_n_closed_trades": last.get("n_closed_trades"),
            "last_win_rate": last.get("win_rate"),
            "last_bayesian_skill_p": last.get("bayesian_skill_p"),
            "last_deflated_sharpe": last.get("deflated_sharpe"),
            "last_independent_bets": last.get("independent_bets"),
            "last_total_realised_pnl_usd": last.get("total_realised_pnl_usd"),
            "trials_scanned": last.get("trials_scanned"),
        })

    promotions = [{"ts": e.get("ts"), "key": e.get("key"),
                    "reason": e.get("reason")}
                   for e in events
                   if isinstance(e, dict) and e.get("action") == "promote"]
    retirements = [{"ts": e.get("ts"), "key": e.get("key"),
                    "reason": e.get("reason")}
                   for e in events
                   if isinstance(e, dict) and e.get("action") == "retire"]
    watches = [{"ts": e.get("ts"), "key": e.get("key"),
                "reason": e.get("reason")}
               for e in events
               if isinstance(e, dict) and e.get("action") == "watch"]
    rejections = [{"ts": e.get("ts"), "key": e.get("key"),
                   "reason": e.get("reason"),
                   "trials_scanned": e.get("trials_scanned"),
                   "n_closed_trades": e.get("n_closed_trades"),
                   "rejected_by": [t.get("test") for t in
                                   (e.get("rejected_by") or [])
                                   if isinstance(t, dict)]}
                  for e in rejected if isinstance(e, dict)]

    trials = sorted({e.get("trials_scanned") for e in rejected
                     if isinstance(e, dict)
                     and isinstance(e.get("trials_scanned"), int)})
    candidates_examined = max(trials) if trials else None

    same = None
    if state["present"] and embedded["present"]:
        same = (sorted(state_blob.get("entries") or {})
                == sorted(emb_blob.get("entries") or {}))

    sec = _base("whitelist", [state["path"], embedded["path"]])
    sec.update({
        "registry_source": state["path"] if state["present"]
        else embedded["path"],
        "state_file_present": state["present"],
        "embedded_present": embedded["present"],
        "state_and_embedded_agree": same,
        "source_divergence_note": (
            "" if same is None else
            ("the state registry and the copy embedded in the priced-edge "
             "file hold the SAME entries"
             if same else
             "the state registry and the copy embedded in the priced-edge "
             "file DISAGREE on which wallets they hold. The state "
             "registry is the live record and is what is tabulated below; "
             "the embedded copy is the snapshot the last gate run wrote. "
             "A disagreement means one of them is stale, and neither can "
             "be preferred without saying which run produced it.")),
        "status_counts": status_counts,
        "status_counts_embedded": status_counts_embedded,
        "n_entries": len(entries),
        "n_entries_embedded": len(emb_blob.get("entries") or {}),
        "n_events": len(events),
        "n_rejected_candidates": len(rejected),
        "entries": rows,
        "promotions": promotions,
        "retirements": retirements,
        "watches": watches,
        "rejections": rejections,
        "candidates_examined": candidates_examined,
        "candidates_examined_note": (
            "this is the N the Deflated Sharpe is corrected for: the "
            "number of candidate wallets that were screened before this "
            "one was chosen. An unknown N is treated as an automatic "
            "rejection of the selection-bias test, not as N=1."),
        "retention_rule": (
            "a retired or rejected wallet leaves the forward cohort and "
            "its history is RETAINED (CFA Institute GIPS 3.A.9), so the "
            "scan's selection bias stays visible instead of being edited "
            "away."),
    })
    return sec


