def _render_criteria_coverage(sec: Dict[str, Any], out: List[str]) -> None:
    out.append("## 2. Criteria coverage — is each criterion enforced?")
    out.append("")
    out.append(_prov_line(sec))
    out.append("")
    if not sec.get("available"):
        out.append(f"> **{sec.get('note', 'unavailable')}**")
        out.append("")
        return
    out.append(f"The specification carries **{sec.get('n_criteria')} "
               f"criteria** and **{sec.get('n_fluke_tests')} fluke tests**. "
               f"Against the four enforcement modules "
               f"(`{'`, `'.join(sec.get('enforcement_modules') or [])}`):")
    out.append("")
    out.append(f"- **Enforced as a gate** (a comparison that can reject a "
               f"wallet): **{sec.get('n_gated')}**")
    out.append(f"- **Enforced as a disclosure** (a required label attached "
               f"to every result): {sec.get('n_disclosed')}")
    out.append(f"- **Computed but not gated:** "
               f"{sec.get('n_implemented_not_gated')}")
    out.append(f"- **Not implemented at all:** {sec.get('n_not_implemented')}")
    out.append(f"- **Analyst choices (no published standard):** "
               f"{sec.get('n_analyst_choice')} of "
               f"{sec.get('n_criteria')}")
    out.append("")
