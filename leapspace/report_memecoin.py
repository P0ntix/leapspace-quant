    out.append("")
    out.append("| Criterion | Threshold | Tag | Authority | Enforced | "
               "Where enforced | Gap / note |")
    out.append("|---|---|---|---|---|---|---|")
    for r in sec.get("rows") or []:
        authority = r.get("authority") or ""
        if r.get("analyst_choice"):
            authority = f"**ANALYST CHOICE** — {authority}"
        kind = r.get("enforcement_kind") or "not-implemented"
        if kind == "gate":
            enforced = "**yes (gate)**"
        elif kind == "disclosure":
            enforced = "yes (disclosure)"
        else:
            enforced = "no"
        where = r.get("where") or ""
        gap = r.get("gap") or ""
        if r.get("note"):
            gap = (gap + " " + r["note"]).strip()
        # Where the code's own threshold differs from the published one,
        # say so rather than letting the threshold column imply the
        # published number is what rejects a wallet.
        applied = r.get("applied_threshold")
        if (applied is not None and r.get("threshold_matches_spec") is False
                and r.get("gated")):
            gap = (gap + f" the code compares against {applied} "
                   f"(`{r.get('applied_threshold_key')}`), not the "
                   f"published {r.get('threshold')}.").strip()
        out.append(
            f"| `{_md_cell(r.get('key'))}` | {_md_cell(_fmt_threshold(r.get('threshold')))} "
            f"| {_md_cell(r.get('tag'))} | {_md_cell(authority)} | {enforced} "
            f"| {_md_cell(where) or '—'} | {_md_cell(gap) or '—'} |")
    out.append("")
    flukes = sec.get("fluke_tests") or []
    if flukes:
        out.append("### Fluke tests in the specification")
        out.append("")
        out.append("| Fluke test | Rejects when | Threshold | Authority |")
        out.append("|---|---|---|---|")
        for t in flukes:
            authority = t.get("authority") or ""
            if t.get("analyst_choice"):
                authority = f"**ANALYST CHOICE** — {authority}"
            out.append(f"| `{_md_cell(t.get('key'))}` "
                       f"| {_md_cell(t.get('rejects_when'))} "
                       f"| {_md_cell(_fmt_threshold(t.get('threshold')))} "
                       f"| {_md_cell(authority)} |")
        out.append("")


