"""
The MEMECOIN-TRADER half of the consolidated report.

WHAT THIS MODULE IS
--------------------
The consolidated report (`leapspace/report.py`) covers the backtest, regime,
gamma and disclosure half of the package. This module covers the OTHER
half: the on-chain memecoin-trader research - the consistency gate, the
31 authority-tagged criteria, the whitelist, the historical pricing
method, the launch-window scan, the social/narrative work, the one source
that needs a key, and the free-data catalogue.

It is a REPORTER, not a researcher. It opens files that already exist and
renders what is in them. It never fetches, never computes a price, never
calls a chain, and never fills a missing input with a plausible default.
Where an input file is absent the section says so and names what is
missing. That is the house rule: an unreachable source yields an
unavailable-source record, NEVER a default or an estimate.

THE PROVENANCE STRINGS
----------------------
Each section carries a `provenance` string:

  LIVE                 - read from a live upstream during this run.
  SYNTHETIC            - generated by this code; never market data.
  DERIVED-FROM-ARTEFACT - derived from files already on disk.

Every section here is DERIVED-FROM-ARTEFACT, because this module only
reads artefacts. The upstream provenance of an artefact (LIVE when it was
fetched, SYNTHETIC when it is a fixture) is carried inside the section
where the artefact records it, so the reader can see how fresh it is.

WHAT THIS REPORT CANNOT SHOW
----------------------------
The markdown opens with a "WHAT THIS DOES NOT SHOW" block. It is not
decoration: the sample is survivorship-selected (the wallets that still
hold the token are the ones that were scanned), the per-wallet price cap
can truncate a wallet's history, the realised PnL is GROSS of gas, DEX
fees and MEV, and most of the 31 criteria are either analyst choices or
things the code computes but does not gate on. A report that hid those
would be a report that over-claims.

STDlib ONLY. This module imports nothing outside the standard library.
"""

