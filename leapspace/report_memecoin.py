def _default_package_root() -> str:
    """The project root: the directory that holds `leapspace/`, `reports/`
    and `data/`. Derived from this file's own location so the module
    works wherever the package is checked out."""
    here = os.path.dirname(os.path.abspath(__file__))
    return os.path.dirname(here)


def _read_json(path: str) -> Tuple[Any, Optional[str]]:
    """Read a JSON file. Returns (data, error). Never raises."""
    if not os.path.exists(path):
        return None, f"file not found: {path}"
    try:
        with open(path, "r", encoding="utf-8") as fh:
            return json.load(fh), None
    except (OSError, ValueError) as exc:
        return None, f"could not read {path}: {type(exc).__name__}: {exc}"


def _read_text(path: str) -> Tuple[Optional[str], Optional[str]]:
    """Read a text file. Returns (text, error). Never raises."""
    if not os.path.exists(path):
        return None, f"file not found: {path}"
    try:
        with open(path, "r", encoding="utf-8") as fh:
            return fh.read(), None
    except (OSError, ValueError) as exc:
        return None, f"could not read {path}: {type(exc).__name__}: {exc}"


def _iso_now() -> str:
    return _dt.datetime.now(_dt.timezone.utc).replace(microsecond=0).isoformat()


def _fmt_usd(v: Any) -> str:
    if v is None:
        return "n/a"
    try:
        f = float(v)
    except (TypeError, ValueError):
        return str(v)
    return f"${f:,.2f}"


def _fmt_pct(v: Any) -> str:
    if v is None:
        return "n/a"
    try:
        return f"{float(v):.1f}%"
    except (TypeError, ValueError):
        return str(v)


def _fmt_price(v: Any) -> str:
    """A USD price at full precision. A price is not a currency amount
    to be rounded to cents, so it is never shown that way."""
    if v is None:
        return "n/a"
    try:
        return f"${float(v):.4e}"
    except (TypeError, ValueError):
        return str(v)


def _fmt_threshold(v: Any) -> str:
    """Render a criterion threshold. A null threshold means the source
    publishes NO number, which must not read like a zero."""
    if v is None:
        return "null (no published number)"
    if isinstance(v, bool):
        return str(v)
    if isinstance(v, (int, float)):
        return f"{v:g}"
    return str(v)


def _md_cell(v: Any) -> str:
    """Make a value safe for a markdown table cell."""
    s = "" if v is None else str(v)
    return s.replace("|", "\\|").replace("\n", " ").strip()


def _absent(name: str, path: str, what_missing: str) -> Dict[str, Any]:
    """The record for a missing input. No default is substituted."""
    return {
        "status": "unavailable",
        "provenance": DERIVED,
        "available": False,
        "section": name,
        "source_file": path,
        "missing": what_missing,
        "note": (f"{name.upper()} IS UNAVAILABLE: {what_missing} "
                 f"(expected at {path}). No value was substituted for it."),
    }


def _base(name: str, sources: Sequence[str]) -> Dict[str, Any]:
    return {
        "status": "ok",
        "provenance": DERIVED,
        "available": True,
        "section": name,
        "source_files": list(sources),
    }


