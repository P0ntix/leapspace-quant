def write_memecoin_report(payload: Optional[Dict[str, Any]] = None,
                          package_root: Optional[str] = None,
                          out_dir: Optional[str] = None) -> Dict[str, str]:
    """Write reports/memecoin_report.md and reports/memecoin_report.json."""
    root = os.path.abspath(package_root or _default_package_root())
    if payload is None:
        payload = build_memecoin_sections(root)
    target = out_dir or os.path.join(root, "reports")
    os.makedirs(target, exist_ok=True)
    md_path = os.path.join(target, "memecoin_report.md")
    json_path = os.path.join(target, "memecoin_report.json")
    artifact = {k: payload[k] for k in ("status", "generated_at",
                                        "package_root", "provenance",
                                        "sections") if k in payload}
    tmp = json_path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        json.dump(artifact, fh, indent=2, default=str)
    os.replace(tmp, json_path)
    with open(md_path, "w", encoding="utf-8") as fh:
        fh.write(render_memecoin_markdown(payload))
    return {"markdown": md_path, "json": json_path}


def main() -> int:
    """Render the report and write both artefacts."""
    payload = build_memecoin_sections()
    paths = write_memecoin_report(payload)
    sections = payload.get("sections") or {}
    print(f"memecoin report written:\n  {paths['markdown']}\n  "
          f"{paths['json']}")
    for name in SECTION_NAMES:
        sec = sections.get(name) or {}
        print(f"  {name:20s} {sec.get('status', '?'):12s} "
              f"{sec.get('provenance', '?')}")
    return 0


