def _render_source_reliability(sec: Dict[str, Any], out: List[str]) -> None:
    out.append("## 8. The free-data catalogue")
    out.append("")
    out.append(_prov_line(sec))
    out.append("")
    if not sec.get("available"):
        out.append(f"> **{sec.get('note', 'unavailable')}**")
        out.append("")
        return
    out.append(f"- **Sources live-probed:** {sec.get('n_live_probed')}")
    out.append(f"- **Verified OK:** {sec.get('n_verified_ok')} "
               f"(recomputed from the file: {sec.get('n_verified_ok_recomputed')})")
    out.append(f"- **Need a key:** {sec.get('n_needs_key')} "
               f"(recomputed: {sec.get('n_needs_key_recomputed')})")
    out.append(f"- **Usable as a fallback:** {sec.get('n_usable_as_fallback')}")
    out.append(f"- **Catalogue generated:** {sec.get('generated_at')}")
    out.append("")
    counts = sec.get("live_status_counts_recomputed") or {}
    if counts:
        out.append("**Live status counts:** "
                   + ", ".join(f"`{k}` {v}" for k, v in sorted(counts.items())))
        out.append("")
    out.append("### Host-level traps that change how results must be read")
    out.append("")
    for t in sec.get("host_traps") or []:
        out.append(f"- **{_md_cell(t.get('trap'))}"
                   + (f" — `{_md_cell(t.get('source'))}`"
                      if t.get("source") else "")
                   + f":** {_md_cell(t.get('detail'))}")
    out.append("")
    out.append("> " + str(sec.get("interpretation_rule")))
    out.append("")


def _render_gaps(sec: Dict[str, Any], out: List[str]) -> None:
    out.append("## 9. Gaps — what this report does NOT show")
    out.append("")
    out.append(_prov_line(sec))
    out.append("")
    out.append(f"**{sec.get('n_gaps')} enumerated gap(s).**")
    out.append("")
    for i, g in enumerate(sec.get("gaps") or [], 1):
        out.append(f"{i}. **{_md_cell(g.get('area'))} — "
                   f"{_md_cell(g.get('id'))}.** {_md_cell(g.get('gap'))} "
                   f"_To close it: {_md_cell(g.get('what_would_close_it'))}_")
    out.append("")


def render_memecoin_markdown(payload: Dict[str, Any]) -> str:
    """Render the memecoin-trader payload as markdown.

    The markdown opens with a "WHAT THIS DOES NOT SHOW" block, because a
    report that lists its gaps last is a report that gets read as a
    clean bill of health.
    """
    sections = payload.get("sections") or payload
    out: List[str] = []
    out.append("# LeapSpace Quant — the memecoin-trader report")
    out.append("")
    out.append(f"Generated: {payload.get('generated_at')}")
    out.append("")
    out.append("> This is the memecoin-trader half of the consolidated "
               "report. It renders artefacts already on disk. It fetched "
               "nothing, priced nothing and estimated nothing.")
    out.append("")

    # --- WHAT THIS DOES NOT SHOW, near the top -------------------------
    out.append("## WHAT THIS DOES NOT SHOW")
    out.append("")
    gate = sections.get("consistency_gate") or {}
    wl = sections.get("whitelist") or {}
    cov = sections.get("criteria_coverage") or {}
    out.append("- **Not a claim about the population of memecoin traders.** "
               "The wallets scanned are survivorship-selected: they are the "
               "ones that still hold the token. A verdict here is a verdict "
               "on those wallets, not a rate.")
    out.append("- **Not a complete performance record.** A per-wallet block "
               "cap means a wallet's early history may never have been "
               "priced, so its realised PnL can be incomplete.")
    out.append("- **Not net of costs.** Realised PnL is GROSS of gas, DEX "
               "fees and MEV.")
    if cov.get("available"):
        out.append(f"- **Not evidence that {cov.get('n_criteria')} standards "
                   f"are applied.** {cov.get('n_gated')} of them can "
                   f"actually reject a wallet; "
                   f"{cov.get('n_analyst_choice')} have no published "
                   f"standard behind them at all.")
    if wl.get("available") and not (wl.get("status_counts") or {}).get(
            "WHITELISTED"):
        out.append("- **Not an endorsement of any wallet.** No wallet holds "
                   "WHITELISTED status in this registry.")
    if wl.get("available") and wl.get("state_and_embedded_agree") is False:
        out.append("- **Not a single consistent whitelist.** The state "
                   "registry and the copy embedded in the priced-edge file "
                   "disagree on which wallets they hold.")
    out.append("- **Not a lead-time measurement.** No wallet has been "
               "measured against a real member-count series; the series "
               "must be collected over time before that is possible.")
    out.append("- **Not a claim that an HTTP 200 means the data arrived.** "
               "On this host a blocked host answers HTTP 200 with an HTML "
               "block page.")
    out.append("")
    out.append("The full enumerated list is in section 9.")
    out.append("")

    _render_consistency_gate(sections.get("consistency_gate") or {}, out)
    _render_criteria_coverage(sections.get("criteria_coverage") or {}, out)
    _render_whitelist(sections.get("whitelist") or {}, out)
    _render_price_method(sections.get("price_method") or {}, out)
    _render_new_meme_path(sections.get("new_meme_path") or {}, out)
    _render_social_edge(sections.get("social_edge") or {}, out)
    _render_keyed_source(sections.get("keyed_source") or {}, out)
    _render_source_reliability(sections.get("source_reliability") or {}, out)
    _render_gaps(sections.get("gaps") or {}, out)

    out.append("---")
    out.append("")
    out.append("*Produced by an automated research system from artefacts on "
               "disk. Not investment advice. A CONSISTENT verdict would mean "
               "the hypothesis survived the gates that ran — nothing more.*")
    return "\n".join(out)


