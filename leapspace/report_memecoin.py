# --------------------------------------------------------------------------

def _section_keyed_source(root: str) -> Dict[str, Any]:
    """The Etherscan adapter: free tier, Pro-only actions, key handling."""
    rel = os.path.join("leapspace", "etherscan.py")
    path = os.path.join(root, rel)
    text, err = _read_text(path)
    if text is None:
        sec = _absent("keyed_source", path,
                       "the Etherscan adapter is missing, so the free-tier "
                       "and Pro-only action lists cannot be read from it")
        sec["missing_input"] = rel
        return sec

    free: List[Dict[str, str]] = []
    pro: List[Dict[str, str]] = []
    m = re.search(r"FREE_TIER_ACTIONS\s*=\s*\{(.*?)\n\}", text, re.S)
    if m:
        for key, value in re.findall(r'"([^"]+)":\s*"([^"]*)"', m.group(1)):
            row = {"action": key, "note": value}
            if "PRO ONLY" in value.upper():
                pro.append(row)
            else:
                free.append(row)

    rel_priced = os.path.join("leapspace", "priced.py")
    priced_text, _ = _read_text(os.path.join(root, rel_priced))
    colon_rule = None
    if priced_text and "COLON" in priced_text:
        for line in priced_text.splitlines():
            if "COLON" in line:
                colon_rule = line.strip()
                break

    # The key is READ FROM THE ENVIRONMENT. Its presence is safe to
    # report; its value is never read, printed, hashed or stored, and no
    # fingerprint of it is produced anywhere in this module.
    #
    # `leapspace.etherscan.has_key()` is the package's own accessor. It
    # returns a BOOLEAN. `api_key()` - which returns the value - is
    # deliberately never called here, and the key's text never enters
    # this module's memory as a string that could be logged or written.
    key_configured = bool(os.environ.get("ETHERSCAN_API_KEY"))
    key_source = ("the process environment (ETHERSCAN_API_KEY), optionally "
                  "loaded from the gitignored .secrets.env beside the "
                  "package")
    key_presence_note = ""
    try:
        from .etherscan import has_key as _has_key
        key_configured = bool(_has_key())
        key_presence_note = (
            "presence was read through the package's own accessor, which "
            "returns a boolean")
    except Exception as exc:  # noqa: BLE001
        # Running the file directly as a script (`python
        # leapspace/report_memecoin.py`) leaves no package context, so
        # the relative import fails. Fall back to an absolute import.
        #
        # The script directory is on sys.path in that mode, and it is the
        # PACKAGE directory, so `leapspace/http.py` shadows the stdlib
        # `http` package that urllib needs. Removing that entry from
        # sys.path for the duration of the import is what makes the
        # fallback work. Still a BOOLEAN: `api_key()`, which returns the
        # value, is never called.
        try:
            import importlib
            _here = os.path.dirname(os.path.abspath(__file__))
            _pkg_parent = os.path.dirname(_here)
            _saved = list(sys.path)
            sys.path = [p for p in sys.path
                        if os.path.abspath(p or ".") != _here]
            if _pkg_parent not in sys.path:
                sys.path.insert(0, _pkg_parent)
            try:
                _has_key = importlib.import_module(
                    "leapspace.etherscan").has_key
                key_configured = bool(_has_key())
                key_presence_note = (
                    "presence was read through the package's own "
                    "accessor, which returns a boolean")
            finally:
                sys.path = _saved
        except Exception as exc2:  # noqa: BLE001
            key_presence_note = (
                f"presence was read from os.environ directly; the package "
                f"accessor was unavailable "
                f"({type(exc).__name__}/{type(exc2).__name__})")

    sec = _base("keyed_source", [rel, rel_priced])
    sec.update({
        "free_tier_actions": free,
        "pro_only_actions": pro,
        "n_free_tier_actions": len(free),
        "n_pro_only_actions": len(pro),
        "free_tier_note": (
            "these actions were verified live against Etherscan V2 on the "
            "date recorded in the adapter's own source comment; anything "
            "not listed as working returns HTTP 200 with status=0 and "
            "message=NOTOK."),
        "http_error_convention": (
            "Etherscan signals failure in the JSON BODY, not the HTTP "
            "status. A bad key, a bad parameter and a rate limit all "
            "return HTTP 200 with {\"status\":\"0\",\"message\":\"NOTOK\"}. "
            "Every response must therefore be checked for status == \"1\"; "
            "an HTTP 200 is never proof of data."),
        "url_separator_rule": (
            "the DefiLlama historical-price endpoint separates chain from "
            "token with a COLON: "
            "https://coins.llama.fi/prices/historical/{unix_ts}/{chain}:"
            "{token}. The comma form returns {\"coins\": {}} and looks "
            "like a dead endpoint - it is not."),
        "url_separator_rule_source_line": colon_rule,
        "api_key_source": key_source,
        "api_key_configured": key_configured,
        "api_key_presence_note": key_presence_note,
        "api_key_handling": (
            "the key is read from the environment at call time. It is "
            "never a literal in source, never written into any artefact, "
            "report, chart or log, and no fingerprint or hash of it is "
            "produced. This section reports only WHETHER one is "
            "configured, never its value."),
        "holder_list_workaround": (
            "Etherscan's own tokenholderlist action is Pro-only and "
            "returns NOTOK on the free tier, so it is not used. Holder "
            "balances are read with the free-tier balance actions, or "
            "reconstructed by netting the token's transfer tape."),
    })
    return sec


