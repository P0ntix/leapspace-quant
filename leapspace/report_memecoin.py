def _find_source(sources: Sequence[Dict[str, Any]], needle: str
                 ) -> Optional[Dict[str, Any]]:
    for s in sources:
        if not isinstance(s, dict):
            continue
        if needle.lower() in str(s.get("name", "")).lower():
            return s
    return None


def _section_source_reliability(root: str) -> Dict[str, Any]:
    """The free-data catalogue and the host traps that shape it."""
    rel = os.path.join("data", "free_data_sources.json")
    path = os.path.join(root, rel)
    blob, err = _read_json(path)
    if blob is None:
        sec = _absent("source_reliability", path,
                       "the free-data catalogue is missing, so the "
                       "live-probe counts and the host-level traps are "
                       "unknown")
        sec["missing_input"] = rel
        return sec
    sources = [s for s in (blob.get("sources") or []) if isinstance(s, dict)]
    summary = blob.get("summary") or {}
    facts = blob.get("host_facts") or {}
    live_counts: Dict[str, int] = {}
    for s in sources:
        st = str(s.get("live_status") or "unknown")
        live_counts[st] = live_counts.get(st, 0) + 1
    n_needs_key = sum(1 for s in sources if s.get("needs_key"))
    n_ok = sum(1 for s in sources if s.get("live_status") == "ok")
    n_fallback = sum(1 for s in sources if s.get("usable_as_fallback"))

    traps: List[Dict[str, Any]] = []
    for key, label in (("network_filter", "URL filter"), ("coin_gecko", "TLS"),
                        ("reddit", "path"), ("ssl", "CA bundle"),
                        ("discord_widget", "widget")):
        if facts.get(key):
            traps.append({"trap": label, "host_fact": key,
                          "detail": facts[key]})
    for needle, label in (("Etherscan API V2 tokenholderlist",
                           "HTTP 200 + NOTOK"),
                          ("ApeWisdom v1.0 JSON API",
                           "docs page at a JSON path"),
                          ("Reddit public JSON", "403 on .json"),
                          ("Reddit public RSS", ".rss works"),
                          ("CoinGecko public API", "TLS handshake failure")):
        s = _find_source(sources, needle)
        if s:
            traps.append({
                "trap": label,
                "source": s.get("name"),
                "live_status": s.get("live_status"),
                "http_status": s.get("http_status"),
                "api_level_error": s.get("api_level_error"),
                "detail": s.get("notes"),
                "usable_as_fallback": s.get("usable_as_fallback"),
            })

    sec = _base("source_reliability", [rel])
    sec.update({
        "generated_at": blob.get("generated_at"),
        "n_sources": len(sources),
        "n_live_probed": len(sources),
        "n_verified_ok": summary.get("verified_ok", n_ok),
        "n_verified_ok_recomputed": n_ok,
        "n_needs_key": summary.get("needs_key", n_needs_key),
        "n_needs_key_recomputed": n_needs_key,
        "n_usable_as_fallback": summary.get("usable_as_fallback", n_fallback),
        "live_status_counts": summary.get("live_status_counts") or live_counts,
        "live_status_counts_recomputed": live_counts,
        "host_facts": facts,
        "host_traps": traps,
        "interpretation_rule": (
            "a status code alone is not proof of data on this host. A "
            "blocked host can answer HTTP 200 with an HTML block page, a "
            "JSON endpoint can answer HTTP 200 with an API-level error, "
            "and a docs page can answer HTTP 200 at a path that is "
            "supposed to return JSON. Every count below is therefore "
            "reported with the shape of the response, not just its "
            "status."),
    })
    return sec


