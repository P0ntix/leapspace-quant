def _price_method_constants(root: str) -> Dict[str, Any]:
    """The pricing constants, read from the source file on disk."""
    rel = os.path.join("leapspace", "priceatblock.py")
    text, err = _read_text(os.path.join(root, rel))
    out: Dict[str, Any] = {"source_file": rel, "error": err,
                            "present": text is not None}
    if text is None:
        return out
    def find(pattern: str) -> Optional[str]:
        m = re.search(pattern, text)
        return m.group(1) if m else None
    out["min_stable_liquidity"] = find(r"MIN_STABLE_LIQUIDITY\s*=\s*([\d_.]+)")
    out["min_weth_liquidity"] = find(r"MIN_WETH_LIQUIDITY\s*=\s*([\d_.]+)")
    out["max_blocks"] = find(r"max_blocks:\s*int\s*=\s*(\d+)")
    out["insufficient_liquidity_status"] = (
        "insufficient_liquidity" if "insufficient_liquidity" in text else None)
    out["docstring_excerpt"] = " ".join(
        (text.split('"""')[1] if text.count('"""') >= 2 else "")
        .split()[:120])
    return out


def _section_price_method(root: str) -> Dict[str, Any]:
    """How the historical prices were obtained, and how good they are."""
    consts = _price_method_constants(root)
    if not consts.get("present"):
        # Without the pricing module there is no method to describe, so
        # the section is UNAVAILABLE. The measured figures below are
        # reported by the README, but a figure with no method behind it
        # is not a method description.
        sec = _absent("price_method",
                       os.path.join(root, consts["source_file"]),
                       "the pricing module is missing, so the price "
                       "method, its liquidity floor and its block cap "
                       "cannot be read from the code that implements them")
        sec["missing_input"] = consts["source_file"]
        sec["measured_accuracy_reference"] = list(PRICE_ACCURACY_CHECKS)
        return sec
    rel_edge = os.path.join("reports", "pepe_priced_edge.json")
    edge, _ = _read_json(os.path.join(root, rel_edge))
    results = (edge or {}).get("results") if isinstance(edge, dict) else None
    results = results or []
    priced_total = sum(int(r.get("n_trades_priced") or 0)
                       for r in results if isinstance(r, dict))
    unpriced_total = sum(int(r.get("n_unpriced") or 0)
                         for r in results if isinstance(r, dict))
    blocks_priced = [r.get("blocks_priced") for r in results
                     if isinstance(r, dict) and r.get("blocks_priced") is not None]
    blocks_skipped = [r.get("blocks_skipped") for r in results
                      if isinstance(r, dict) and r.get("blocks_skipped") is not None]

    # Cross-check the measured accuracy table against the README, so the
    # report says whether the row it quotes is on disk.
    rel_readme = "README.md"
    readme, _ = _read_text(os.path.join(root, rel_readme))
    checks: List[Dict[str, Any]] = []
    for row in PRICE_ACCURACY_CHECKS:
        r = dict(row)
        found = False
        if readme:
            # The README prints e.g. $1.2370e-06.
            pretty = f"${row['pool_price_usd']:.4e}"
            found = pretty in readme
        r["found_in_readme"] = found
        r["readme_file"] = rel_readme if readme else None
        checks.append(r)

    # A second, independent on-disk measurement: the pool-vs-index probe.
    rel_probe = os.path.join("reports", "probe_pool_vs_llama.json")
    probe, _ = _read_json(os.path.join(root, rel_probe))
    probe_summary: Optional[Dict[str, Any]] = None
    if isinstance(probe, dict):
        samples = probe.get("samples") or []
        errs = [abs(float(s.get("pct_error"))) for s in samples
                if isinstance(s, dict) and isinstance(s.get("pct_error"),
                                                      (int, float))]
        if samples:
            probe_summary = {
                "source_file": rel_probe,
                "n_samples": len(samples),
                "max_abs_pct_error": max(errs) if errs else None,
                "median_abs_pct_error": (sorted(errs)[len(errs) // 2]
                                         if errs else None),
                "note": ("pool-derived price against the reference index "
                         "at fixed blocks; pct_error is already in percent"),
            }

    sec = _base("price_method", [consts["source_file"], rel_edge,
                                  rel_readme, rel_probe])
    sec.update({
        "method": (
            "Uniswap V2 pair reserves read at each trade's own block, via "
            "a keyless archive RPC. The package asks the V2 factory, AT "
            "that block, which pair existed for (token, USDC), then reads "
            "that pair's getReserves() at the same block and takes "
            "reserve(quote) / reserve(token) with decimals applied. A "
            "token whose deep pair is quoted in WETH is priced in WETH and "
            "multiplied by the WETH/USD price read from the deep "
            "WETH/USDC pair at the same block. No price API is required "
            "for the pool route."),
        "liquidity_floor": {
            "stable_quote_min": consts.get("min_stable_liquidity"),
            "weth_quote_min": consts.get("min_weth_liquidity"),
            "rejection_status": consts.get("insufficient_liquidity_status"),
            "note": ("a pair whose quote side holds less than the floor is "
                     "REJECTED and the price is reported as unavailable "
                     "rather than as a number, so a nearly-empty pool "
                     "cannot manufacture a price"),
        },
        "per_wallet_block_cap": {
            "max_blocks": consts.get("max_blocks"),
            "source": consts["source_file"],
            "consequence": (
                "the cap limits how many DISTINCT blocks one wallet scan "
                "prices. When it bites, the most RECENT blocks are priced "
                "- those are the trades that decide whether the wallet has "
                "a live edge - and the number of blocks NOT priced is "
                "reported rather than hidden. A wallet's EARLY history can "
                "therefore be missing from its realised PnL, and its "
                "PnL can be incomplete without the PnL itself being "
                "wrong."),
            "blocks_priced_recorded": blocks_priced or None,
            "blocks_skipped_recorded": blocks_skipped or None,
        },
        "measured_accuracy_vs_defillama": checks,
        "measured_accuracy_note": (
            "the pool-derived price is compared against DefiLlama's "
            "historical index price. The percentage errors above are the "
            "measured ones recorded in the package README's verification "
            "table; the third row is large because the pool was new and "
            "shallow, which is exactly the case the liquidity floor "
            "targets."),
        "independent_pool_vs_index_probe": probe_summary,
        "priced_totals": {
            "n_trades_priced": priced_total,
            "n_unpriced": unpriced_total,
            "source_file": rel_edge,
        },
        "fee_basis": (
            "the realised PnL is GROSS of gas, DEX fees and MEV. None of "
            "those are observable from ERC-20 transfers alone, so a net "
            "figure would need per-swap gas and fee logs. Every PnL "
            "number in this report is on that gross basis."),
    })
    return sec


