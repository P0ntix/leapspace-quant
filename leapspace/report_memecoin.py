def build_memecoin_sections(package_root: Optional[str] = None
                            ) -> Dict[str, Any]:
    """Build the machine-readable memecoin-trader payload.

    Every section is built from files that exist on disk. Where a file
    is missing the section records the absence and names what is
    missing - it never substitutes a default.

    The returned dict exposes each section BOTH at the top level and
    under `payload["sections"]`, so a caller can use either shape. The
    JSON artefact carries the canonical `sections` mapping.
    """
    root = os.path.abspath(package_root or _default_package_root())
    sections: Dict[str, Any] = {}
    sections["consistency_gate"] = _section_consistency_gate(root)
    sections["criteria_coverage"] = _section_criteria_coverage(root)
    sections["whitelist"] = _section_whitelist(root)
    sections["price_method"] = _section_price_method(root)
    sections["new_meme_path"] = _section_new_meme_path(root)
    sections["social_edge"] = _section_social_edge(root)
    sections["keyed_source"] = _section_keyed_source(root)
    sections["source_reliability"] = _section_source_reliability(root)
    sections["gaps"] = _section_gaps(root, sections)

    payload: Dict[str, Any] = {
        "status": "ok",
        "generated_at": _iso_now(),
        "package_root": root,
        "provenance": DERIVED,
        "sections": sections,
    }
    # Mirror the sections at the top level for convenience.
    for name in SECTION_NAMES:
        payload[name] = sections[name]
    return payload


