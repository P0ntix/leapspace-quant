"""
Provenance and disclosure primitives.

Every datum that enters this system carries a provenance record. The rule the
user set: never invent real data; if it is dummy data it must be disclosed.

Three kinds:
  LIVE      -- fetched from a real upstream source during this run.
  CACHE     -- served from a local file that was itself populated from a
               real upstream source (the cache records that source + fetch
               time, so it is never mistaken for fresh data).
  SYNTHETIC -- generated by this code for self-tests and demos. Always
               carries an explicit disclosure string that is rendered in
               every report that contains it.

Nothing else is permitted to produce a number. If a source is unreachable the
correct outcome is an unavailable-source record, never a plausible guess.
"""

from __future__ import annotations

import datetime as _dt
import json
import os
import time
from dataclasses import dataclass, field, asdict
from typing import Any, Dict, List, Optional

LIVE = "LIVE"
CACHE = "CACHE"
SYNTHETIC = "SYNTHETIC"

SYNTHETIC_DISCLOSURE = (
    "SYNTHETIC DATA — generated by leapspace.selftest / synthetic fixtures. "
    "This is NOT market data and must never be used to make trading decisions."
)


def utcnow_iso() -> str:
    return _dt.datetime.now(_dt.timezone.utc).replace(microsecond=0).isoformat()


@dataclass
class Provenance:
    """Where a piece of data came from, and whether it is real."""

    source: str                      # short identifier, e.g. "yahoo.chart"
    kind: str = LIVE                 # LIVE | CACHE | SYNTHETIC
    url: Optional[str] = None
    fetched_at: str = field(default_factory=utcnow_iso)
    fetched_at_epoch: float = field(default_factory=time.time)
    note: str = ""
    params: Dict[str, Any] = field(default_factory=dict)

    @property
    def is_real(self) -> bool:
        return self.kind in (LIVE, CACHE)

    @property
    def is_synthetic(self) -> bool:
        return self.kind == SYNTHETIC

    def disclosure(self) -> str:
        if self.kind == SYNTHETIC:
            return SYNTHETIC_DISCLOSURE
        if self.kind == CACHE:
            return (f"Cached data — originally fetched {self.fetched_at} "
                    f"from {self.source}"
                    + (f" ({self.url})" if self.url else "")
                    + (f". {self.note}" if self.note else ""))
        return (f"Live data from {self.source} fetched {self.fetched_at}"
                + (f" ({self.url})" if self.url else "")
                + (f". {self.note}" if self.note else ""))

    def to_dict(self) -> Dict[str, Any]:
        d = asdict(self)
        d["disclosure"] = self.disclosure()
        d["is_real"] = self.is_real
        d["is_synthetic"] = self.is_synthetic
        return d


@dataclass
class DataPoint:
    """A value plus its provenance. Use .value; never lose the provenance."""

    value: Any
    provenance: Provenance

    @property
    def is_real(self) -> bool:
        return self.provenance.is_real

    @property
    def is_synthetic(self) -> bool:
        return self.provenance.is_synthetic


class SourceUnavailable(Exception):
    """Raised when a required source cannot be reached.

    Callers catch this and record an unavailable-source entry. It must never
    be converted into a default or an estimate.
    """


def unavailable(source: str, url: Optional[str], reason: str) -> Dict[str, Any]:
    return {
        "source": source,
        "url": url,
        "reason": reason,
        "at": utcnow_iso(),
        "disclosure": (f"SOURCE UNAVAILABLE — {source} could not be reached "
                       f"({reason}). No data was substituted for it."),
    }


def write_json(path: str, payload: Any) -> str:
    """Atomic JSON write (write to .tmp then os.replace)."""
    os.makedirs(os.path.dirname(os.path.abspath(path)) or ".", exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        json.dump(payload, fh, indent=2, default=str)
    os.replace(tmp, path)
    return path


def read_json(path: str, default: Any = None) -> Any:
    if not os.path.exists(path):
        return default
    try:
        with open(path, "r", encoding="utf-8") as fh:
            return json.load(fh)
    except (OSError, ValueError):
        return default
